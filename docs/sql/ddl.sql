-- Clean drop existing objects in dependency order (safe re-execution)
DROP TABLE IF EXISTS corroboration CASCADE;
DROP TABLE IF EXISTS sighting CASCADE;
DROP TABLE IF EXISTS squad_membership CASCADE;
DROP TABLE IF EXISTS pet_report CASCADE;
DROP TABLE IF EXISTS user_profile CASCADE;

-- ----------------------------------------------------------------------------
-- 1. USER PROFILE (user_profile)
-- Represents authenticated users (owners, search squad volunteers, spotters)
-- ----------------------------------------------------------------------------
CREATE TABLE user_profile
(
    user_profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_key    UUID                        NOT NULL,
    oauth_key       VARCHAR(255)                NOT NULL,
    display_name    VARCHAR(100)                NOT NULL,
    email           VARCHAR(255)                NOT NULL,
    avatar_url      VARCHAR(1024),
    phone_number    VARCHAR(30),
    created         TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX idx_user_profile_external_key ON user_profile (external_key);
CREATE UNIQUE INDEX idx_user_profile_oauth_key ON user_profile (oauth_key);
CREATE UNIQUE INDEX idx_user_profile_email ON user_profile (email);

-- ----------------------------------------------------------------------------
-- 2. PET REPORT (pet_report)
-- Represents active or resolved missing pet cases broadcast to the community
-- Direct photo_url points to primary reference image in cloud storage
-- ----------------------------------------------------------------------------
CREATE TABLE pet_report
(
    pet_report_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_key                UUID                        NOT NULL,
    owner_id                    BIGINT                      NOT NULL,
    pet_name                    VARCHAR(100)                NOT NULL,
    species                     VARCHAR(50)                 NOT NULL,
    breed                       VARCHAR(100),
    color_markings              VARCHAR(255)                NOT NULL,
    collar_description          VARCHAR(255),
    is_microchipped             BOOLEAN                     NOT NULL DEFAULT FALSE,
    photo_url                   VARCHAR(1024),
    last_seen_timestamp         TIMESTAMP WITH TIME ZONE    NOT NULL,
    last_seen_latitude          DOUBLE PRECISION            NOT NULL,
    last_seen_longitude         DOUBLE PRECISION            NOT NULL,
    last_seen_address           VARCHAR(255),
    status                      VARCHAR(30)                 NOT NULL DEFAULT 'ACTIVE_SEARCH',
    resolution_notes            TEXT,
    created                     TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated                     TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pet_report_owner
        FOREIGN KEY (owner_id)
        REFERENCES user_profile (user_profile_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_pet_report_status
        CHECK (status IN ('ACTIVE_SEARCH', 'REUNITED', 'CLOSED'))
);

CREATE UNIQUE INDEX idx_pet_report_external_key ON pet_report (external_key);
CREATE INDEX idx_pet_report_owner_id ON pet_report (owner_id);
CREATE INDEX idx_pet_report_status ON pet_report (status);
CREATE INDEX idx_pet_report_last_seen_timestamp ON pet_report (last_seen_timestamp);
CREATE INDEX idx_pet_report_coords ON pet_report (last_seen_latitude, last_seen_longitude);

-- ----------------------------------------------------------------------------
-- 3. SQUAD MEMBERSHIP (squad_membership)
-- Many-to-many join connecting volunteers who mobilized for a specific pet
-- ----------------------------------------------------------------------------
CREATE TABLE squad_membership
(
    squad_membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT                      NOT NULL,
    pet_report_id       BIGINT                      NOT NULL,
    joined              TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active           BOOLEAN                     NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_squad_member_user
        FOREIGN KEY (user_id)
        REFERENCES user_profile (user_profile_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_squad_member_report
        FOREIGN KEY (pet_report_id)
        REFERENCES pet_report (pet_report_id)
        ON DELETE CASCADE,

    CONSTRAINT uq_squad_membership_user_report
        UNIQUE (user_id, pet_report_id)
);

CREATE INDEX idx_squad_membership_user_id ON squad_membership (user_id);
CREATE INDEX idx_squad_membership_pet_report_id ON squad_membership (pet_report_id);

-- ----------------------------------------------------------------------------
-- 4. SIGHTING (sighting)
-- Geotagged observation submitted by a spotter with travel vector & evidence photo
-- ----------------------------------------------------------------------------
CREATE TABLE sighting
(
    sighting_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_key         UUID                        NOT NULL,
    pet_report_id        BIGINT                      NOT NULL,
    spotter_id           BIGINT                      NOT NULL,
    photo_url            VARCHAR(1024),
    sighting_timestamp   TIMESTAMP WITH TIME ZONE    NOT NULL,
    latitude             DOUBLE PRECISION            NOT NULL,
    longitude            DOUBLE PRECISION            NOT NULL,
    location_description VARCHAR(255),
    direction            VARCHAR(20),
    direction_notes      VARCHAR(255),
    notes                TEXT,
    created              TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sighting_pet_report
        FOREIGN KEY (pet_report_id)
        REFERENCES pet_report (pet_report_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_sighting_spotter
        FOREIGN KEY (spotter_id)
        REFERENCES user_profile (user_profile_id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_sighting_direction
        CHECK (direction IS NULL OR direction IN (
            'NORTH', 'NORTHEAST', 'EAST', 'SOUTHEAST',
            'SOUTH', 'SOUTHWEST', 'WEST', 'NORTHWEST',
            'STATIONARY', 'UNKNOWN'
        ))
);

CREATE UNIQUE INDEX idx_sighting_external_key ON sighting (external_key);
CREATE INDEX idx_sighting_pet_report_id ON sighting (pet_report_id);
CREATE INDEX idx_sighting_spotter_id ON sighting (spotter_id);
CREATE INDEX idx_sighting_timestamp ON sighting (sighting_timestamp);
CREATE INDEX idx_sighting_coords ON sighting (latitude, longitude);

-- ----------------------------------------------------------------------------
-- 5. CORROBORATION (corroboration)
-- Community verification / upvoting of a reported sighting lead
-- ----------------------------------------------------------------------------
CREATE TABLE corroboration
(
    corroboration_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sighting_id         BIGINT                      NOT NULL,
    user_id             BIGINT                      NOT NULL,
    is_confirmed        BOOLEAN                     NOT NULL DEFAULT TRUE,
    corroboration_notes VARCHAR(500),
    created             TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_corroboration_sighting
        FOREIGN KEY (sighting_id)
        REFERENCES sighting (sighting_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_corroboration_user
        FOREIGN KEY (user_id)
        REFERENCES user_profile (user_profile_id)
        ON DELETE CASCADE,

    CONSTRAINT uq_corroboration_sighting_user
        UNIQUE (sighting_id, user_id)
);

CREATE INDEX idx_corroboration_sighting_id ON corroboration (sighting_id);
CREATE INDEX idx_corroboration_user_id ON corroboration (user_id);
